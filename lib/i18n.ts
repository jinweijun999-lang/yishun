export type TranslationKey = keyof typeof translations["en"];

export function normalizeLocale(value?: string | null): Locale | null {
  if (!value) {
    return null;
  }
  const lower = value.toLowerCase();
  if (LOCALE_ALIASES[lower]) {
    return LOCALE_ALIASES[lower];
  }
  const prefix = lower.split("-")[0];
  return LOCALE_ALIASES[prefix] ?? null;
}

export function pickLocaleFromAcceptLanguage(
  header?: string | null
): Locale | null {
  if (!header) {
    return null;
  }
  const locales = header
    .split(",")
    .map((part) => part.trim().split(";")[0])
    .filter(Boolean);
  for (const locale of locales) {
    const normalized = normalizeLocale(locale);
    if (normalized) {
      return normalized;
    }
  }
  return null;
}

export function resolveLocale(options: {
  cookieLocale?: string | null;
  acceptLanguage?: string | null;
  defaultLocale?: Locale;
}): Locale {
  const fromCookie = normalizeLocale(options.cookieLocale);
  if (fromCookie) {
    return fromCookie;
  }
  const fromHeader = pickLocaleFromAcceptLanguage(options.acceptLanguage);
  if (fromHeader) {
    return fromHeader;
  }
  return options.defaultLocale ?? DEFAULT_LOCALE;
}

export function getLocaleFromRequest(request: NextRequest): Locale {
  return resolveLocale({
    cookieLocale: request.cookies.get(LOCALE_COOKIE)?.value,
    acceptLanguage: request.headers.get("accept-language"),
  });
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dictionary = translations[locale] ?? translations[DEFAULT_LOCALE];
  const template = dictionary[key] ?? translations[DEFAULT_LOCALE][key] ?? key;
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, name) => {
    const value = vars[name];
    return value === undefined ? "" : String(value);
  });
}
