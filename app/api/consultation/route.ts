function getPrompt(locale: Locale) {
  return locale === "zh-CN" ? SYSTEM_PROMPT_ZH : SYSTEM_PROMPT_EN;
}

function isGender(value: string): value is Gender {
  return value === "male" || value === "female" || value === "other";
}

async function syncMembershipCredits(user: UserWithAccrual): Promise<UserWithAccrual> {
  const tier = normalizeMembershipTier(user.planTier);
  const update = getAccruedCreditsUpdate({
    tier,
    currentCredits: user.consultationCredits,
    lastAccruedAt: user.lastCreditsAccruedAt ?? null,
  });
  if (!update.changed) {
    return user;
  }
  const data = {
    consultationCredits: update.credits,
    lastCreditsAccruedAt: update.lastAccruedAt,
  };
  return prisma.user.update({
    where: { id: user.id },
    data,
  });
}

function buildUserContext(locale: Locale, question: string, category?: string | null) {
  if (locale === "zh-CN") {
    return `用户问题：${question}\n类别提示（可选）：${category ?? "无"}`;
  }
  return `User question: ${question}\nCategory hint (optional): ${category ?? "none"}`;
}

function validateResponse(result: ConsultationResponse): boolean {
  if (!result || typeof result !== "object") {
    return false;
  }
  if (result.status !== "ok" && result.status !== "not_applicable") {
    return false;
  }
  if (typeof result.question_context !== "string") {
    return false;
  }
  if (typeof result.interpretation !== "string") {
    return false;
  }
  if (result.status === "ok") {
    if (!Array.isArray(result.signals_used) || result.signals_used.length === 0) {
      return false;
    }
    if (!result.action_guidance || typeof result.action_guidance !== "object") {
      return false;
    }
    if (
      typeof result.action_guidance.do !== "string" ||
      typeof result.action_guidance.avoid !== "string"
    ) {
      return false;
    }
  }
  return true;
}

async function runConsultation(
  locale: Locale,
  question: string,
  category: string | null,
  baziProfile: object
): Promise<ConsultationResponse> {
  const systemPrompt = getPrompt(locale);
  const userContext = buildUserContext(locale, question, category);
  const payload = JSON.stringify(baziProfile, null, 2);

  const models = Array.from(new Set(GOOGLE_MODELS));
  const errors: string[] = [];

  for (const model of models) {
    try {
      const response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${GOOGLE_API_KEY}`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [
              {
                parts: [
                  {
                    text:
                      systemPrompt +
                      "\n\nBa Zi Profile (precomputed):\n" +
                      payload +
                      "\n\n" +
                      userContext,
                  },
                ],
              },
            ],
            generationConfig: {
              temperature: 0.4,
              responseMimeType: "application/json",
            },
          }),
        }
      );

      if (!response.ok) {
        const error = await response.text();
        throw new Error(`Google API Error: ${response.status} - ${error}`);
      }

      const data = await response.json();
      const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!text) {
        throw new Error("Empty response");
      }

      try {
        return JSON.parse(text) as ConsultationResponse;
      } catch {
        const jsonMatch = text.match(/\{[\s\S]*\}/);
        if (jsonMatch) {
          return JSON.parse(jsonMatch[0]) as ConsultationResponse;
        }
        throw new Error("Invalid JSON response");
      }
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      errors.push(`${model}: ${message}`);
    }
  }

  throw new Error(errors.join(" | "));
}

export async function POST(request: NextRequest) {
  const locale = getLocaleFromRequest(request);
  const t = (key: Parameters<typeof translate>[1]) => translate(locale, key);
  const session = await getSessionPayload(request);
  if (!session) {
    return NextResponse.json({ error: t("errors.unauthorized") }, { status: 401 });
  }

  if (!GOOGLE_API_KEY) {
    return NextResponse.json(
      { error: t("errors.googleKeyMissing") },
      { status: 500 }
    );
  }

  const body = await request.json();
  const question = typeof body?.question === "string" ? body.question.trim() : "";
  const category = typeof body?.category === "string" ? body.category : null;

  if (!question) {
    return NextResponse.json(
      { error: t("errors.questionRequired") },
      { status: 400 }
    );
  }

  const user = await prisma.user.findUnique({ where: { id: session.sub } });
  if (!user) {
    return NextResponse.json({ error: t("errors.userNotFound") }, { status: 404 });
  }

  const syncedUser = await syncMembershipCredits(user);

  if (!syncedUser.birthDate || !syncedUser.birthTime || !syncedUser.gender) {
    return NextResponse.json(
      { error: t("errors.profileIncomplete") },
      { status: 400 }
    );
  }

  if (syncedUser.consultationCredits <= 0) {
    return NextResponse.json(
      { error: t("errors.creditsRequired") },
      { status: 402 }
    );
  }

  const creditReservation = await prisma.user.updateMany({
    where: { id: syncedUser.id, consultationCredits: { gte: 1 } },
    data: { consultationCredits: { decrement: 1 } },
  });
  if (creditReservation.count !== 1) {
    return NextResponse.json(
      { error: t("errors.creditsRequired") },
      { status: 402 }
    );
  }

  const normalizedGender = syncedUser.gender.toLowerCase();
  if (!isGender(normalizedGender)) {
    return NextResponse.json(
      { error: t("errors.invalidGender") },
      { status: 400 }
    );
  }

  const bazi = computeFourPillars({
    birthDate: syncedUser.birthDate,
    birthTime: syncedUser.birthTime,
    gender: normalizedGender,
    longitude: syncedUser.longitude ?? null,
    latitude: syncedUser.latitude ?? null,
    timezoneOffsetMinutes: syncedUser.timezoneOffsetMinutes ?? null,
    timezoneName: syncedUser.timezoneName ?? null,
  });
  const baziProfile = buildBaziProfile(bazi);

  let response: ConsultationResponse | null = null;
  let attempt = 0;
  while (attempt < 2) {
    attempt += 1;
    response = await runConsultation(locale, question, category, baziProfile);
    if (validateResponse(response)) {
      break;
    }
    response = null;
  }

  if (!response) {
    await prisma.user.update({
      where: { id: syncedUser.id },
      data: { consultationCredits: { increment: 1 } },
    });
    return NextResponse.json(
      { error: t("errors.consultationFailed") },
      { status: 500 }
    );
  }

  const isApplicable = response.status === "ok";

  await prisma.consultation.create({
    data: {
      userId: syncedUser.id,
      question,
      category,
      status: response.status,
      response: response as Prisma.InputJsonValue,
    },
  });

  let creditsRemaining = syncedUser.consultationCredits - 1;
  if (!isApplicable) {
    const refunded = await prisma.user.update({
      where: { id: syncedUser.id },
      data: { consultationCredits: { increment: 1 } },
      select: { consultationCredits: true },
    });
    creditsRemaining = refunded.consultationCredits;
  }

  return NextResponse.json({
    status: response.status,
    result: response,
    creditsRemaining,
    creditPolicy: isApplicable ? "1 ask credit consumed." : "Question was not applicable; reserved ask credit was returned.",
  });
}
